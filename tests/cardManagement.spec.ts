import { test, expect, type Page } from '@playwright/test';
async function create(page: Page, title: string) {
  await page.route('https://en.wiktionary.org/**', r => r.fulfill({ json: { query: { pages: [] } } }));
  await page.goto('/files/new');
  await page.locator('#deck-title').fill(title);
  await page.locator('textarea').fill('water 水');
  await page.locator('button[type=submit]').click();
  await page.waitForURL(/flashcards$/);
  return page.url();
}
test('add another, save one side on Close, empty Close, and delete a card', async ({ page }) => {
  const url = await create(page, 'Cards');
  await page.goto(url.replace(/\/flashcards$/, ''));
  const open = () => page.getByRole('button', { name: /^(Add card|添加卡片)$/ }).click();
  const close = () => page.locator('dialog').getByRole('button', { name: /^(Close|关闭)$/ }).click();
  await open(); await close();
  await expect(page.locator('.entry-item')).toHaveCount(1);
  await open();
  await page.locator('dialog textarea').nth(0).fill('boek');
  await page.locator('dialog textarea').nth(1).fill('书');
  await page.locator('dialog').getByRole('button', { name: /^(Add another|再添加一张)$/ }).click();
  await expect(page.locator('dialog textarea').nth(0)).toHaveValue('');
  await expect(page.locator('.entry-item')).toHaveCount(2);
  await page.locator('dialog textarea').nth(1).fill('世界');
  await close();
  await expect(page.locator('dialog')).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.entry-item')).toHaveCount(3);
  page.once('dialog', d => d.dismiss());
  await page.locator('.entry-item').last().getByRole('button', { name: /Delete card|删除卡片/ }).click();
  await expect(page.locator('.entry-item')).toHaveCount(3);
  page.once('dialog', d => d.accept());
  await page.locator('.entry-item').last().getByRole('button', { name: /Delete card|删除卡片/ }).click();
  await expect(page.locator('.entry-item')).toHaveCount(2);
  await page.reload();
  await expect(page.locator('.entry-item')).toHaveCount(2);
});
test('delete the last card from 3D review', async ({ page }) => {
  const url = await create(page, 'Delete in 3D');
  await page.goto(url.replace(/\/flashcards$/, ''));
  await page.getByRole('button', { name: /^(Add card|添加卡片)$/ }).click();
  await page.locator('dialog textarea').nth(0).fill('boek');
  await page.locator('dialog textarea').nth(1).fill('书');
  await page.locator('dialog').getByRole('button', { name: /^(Close|关闭)$/ }).click();
  await page.goto(url);
  await expect(page.locator('canvas')).toBeVisible();
  await page.locator('[data-control=expand]').click();
  await page.locator('[data-control=edit]').click();
  page.once('dialog', d => d.accept());
  await page.locator('dialog').getByRole('button', { name: /^(Delete|删除)$/ }).click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(page.locator('.world-heading [role=status]')).toContainText('1 / 2');
  await expect(page.locator('canvas')).toHaveAttribute('aria-description', /boek|书/);
  if (await page.locator('[data-control=expand]').getAttribute('aria-expanded') !== 'true') await page.locator('[data-control=expand]').click();
  await page.locator('[data-control=edit]').click();
  page.once('dialog', d => d.accept());
  await page.locator('dialog').getByRole('button', { name: /^(Delete|删除)$/ }).click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await page.goto(url.replace(/\/flashcards$/, ''));
  await expect(page.locator('.entry-item')).toHaveCount(0);
});
test('Speed Run follows the landing page order, including manual reordering', async ({ page }) => {
  await create(page, 'First deck'); await create(page, 'Second deck');
  await page.goto('/');
  await expect(page.locator('.file-list-title')).toHaveText(['Second deck', 'First deck']);
  await page.locator('.deck-drag-handle').first().press('ArrowDown');
  await expect(page.locator('.file-list-title')).toHaveText(['First deck', 'Second deck']);
  await expect(page.locator('.reorderable-file-list')).toHaveAttribute('aria-busy', 'false');
  await page.goto('/speed-run');
  await expect(page.locator('.run-deck strong')).toHaveText(['First deck', 'Second deck']);
});
